from .volatility import REPRESENTATIVE, engine, vol_dir

log = logging.getLogger(__name__)
VOL_MODELS = ["const", "hv21", "hv63", "ewma", "garch_n", "garch_t", "gjr_t"]
WIN = {"k1": "1d", "cum5": "5d", "cum21": "21d"}


def _cols(t: pd.DataFrame) -> pd.DataFrame:
    """Order (period, window) columns as dev 1d/5d/21d, holdout 1d/5d/21d and flatten the names."""
    order = [(p, w) for p in ("dev", "holdout") for w in ("k1", "cum5", "cum21") if (p, w) in t.columns]
    t = t[order]
    t.columns = [f"{p} {WIN[w]}" for p, w in t.columns]
    return t


def _read(p: Path):
    return pd.read_csv(p) if p.exists() else None


def run_vol_report(cfg: dict) -> Path:
    from .runner import prepare, resolve_split

    vd = vol_dir(cfg)
    out = report_dir(cfg)
    fig = out / "figures"
    fig.mkdir(parents=True, exist_ok=True)
    md, fs, panel = prepared = prepare(cfg)
    split = resolve_split(cfg, panel)
    dates = fs.dates if pd.api.types.is_numeric_dtype(fs.dates) else pd.to_datetime(fs.dates)
    hmark = dates[split["holdout_start"]]
    L = [f"# Volatility research tables - profile `{cfg['name']}`", "",
         "_Machine-generated by `python -m commodity_research.cli vol-report`. Do not edit by hand._", "",
         f"- Dataset: `{md.name}`; estimation sample rows 0-{split['holdout_start'] - 1}; development OOS "
         f"{split['dev_start']}-{split['holdout_start'] - 1}; holdout {split['holdout_start']}-{split['end'] - 1}", ""]

    # ------------------------------------------------------------------ Part I
    summ = _read(vd / "diagnostics_summary.csv")
    if summ is not None:
        L += ["## Part I. Stylised facts", "", "Share of series rejecting each null at 5% and after Benjamini-Hochberg FDR (q = 0.10):", ""]
        L.append(md_table(summ[["sample", "test", "n_series", "share_p<0.05", "share_BH_q0.1", "median_p"]], "{:.3f}"))
        bym = pd.read_csv(vd / "diagnostics_by_market.csv")
        L += ["", "By market (estimation sample; medians and rejection shares at 5%):", "", md_table(bym, "{:.3f}"), ""]
        a = pd.read_csv(vd / "diagnostics_assets_estimation.csv", index_col=0)
        rep = a.loc[[s for s in REPRESENTATIVE if s in a.index]]
        cols = ["vol_ann", "skew", "exkurt", "jb_p", "lb_r_10_p", "lb_r2_10_p", "arch_lm_p", "alpha", "beta", "persistence",
                "half_life_days", "nu", "gjr_gamma", "lr_gjr_p", "lb_z2_p", "arch_lm_z_p", "sb_joint_p"]
        L += ["Representative series (estimation sample; GARCH(1,1)-t fitted in-sample for residual diagnostics):", "",
              md_table(rep[cols].reset_index().rename(columns={"index": "series"}), "{:.3f}"), ""]
        s = pd.read_csv(vd / "diagnostics_spreads_estimation.csv", index_col=0)
        from ..volatility.diagnostics import bh_fdr

        L += [f"Target spreads: Ljung-Box on spread returns (10 lags) rejects for {np.mean(s['lb_r_10_p'] < 0.05):.1%} of "
              f"{len(s)} targets at 5% ({bh_fdr(s['lb_r_10_p'].to_numpy()).mean():.1%} after BH-FDR) in the estimation sample.", ""]
        sp = _read(vd / "diagnostics_subperiods.csv")
        if sp is not None:
            L += ["Sub-period stability (share of assets rejecting after BH-FDR, Ljung-Box 10 lags):", "", md_table(sp, "{:.3f}"), ""]
        figdata = json.loads((vd / "diagnostics_figdata.json").read_text())
        show = [x for x in ("LME_CA_Close", "JPX_Gold_Standard_Futures_Close", "US_Stock_XLE_adj_close", "FX_AUDUSD") if x in figdata]
        show = show or list(figdata)[:4]
        if show:
            VF.fig_acf(figdata, show, fig / "v01_acf_returns_vs_squared.png", f"estimation sample (rows 0-{split['holdout_start'] - 1})")
            VF.fig_qq(figdata, show, fig / "v02_qq_plots.png", f"estimation sample (rows 0-{split['holdout_start'] - 1})")
        VF.fig_diag_shares(summ, fig / "v03_test_rejection_shares.png",
                           f"Estimation sample = rows 0-{split['holdout_start'] - 1} (pre-holdout); holdout = rows "
                           f"{split['holdout_start']}-{split['end'] - 1}. {len(fs.assets)} assets, {len(panel.targets)} target spreads.")

    # ------------------------------------------------------------------ Part II
    vs = _read(vd / "volforecast_summary.csv")
    if vs is not None:
        pan = pd.read_csv(vd / "volforecast_panel_dm.csv")
        L += ["## Part II. Volatility forecasting (out of sample)", "",
              "Mean over assets of QLIKE(model) - QLIKE(EWMA) (negative = better than EWMA), MCS inclusion share:", ""]
        t = vs.pivot_table(index="model", columns=["period", "window"], values="mean_qlike_minus_ewma").reindex(VOL_MODELS)
        t = _cols(t)
        L += [md_table(t.reset_index(), "{:+.4f}"), ""]
        t = vs.pivot_table(index="model", columns=["period", "window"], values="mcs_inclusion_share").reindex(VOL_MODELS)
        t = _cols(t)
        L += ["MCS (90%) inclusion share across assets:", "", md_table(t.reset_index(), "{:.2f}"), ""]
        x = pan[(pan.assets == "all") & (pan.subset == "all") & (pan.proxy == "sq")]
        t = x.pivot_table(index=["hypothesis", "model_a", "model_b"], columns=["period", "window"], values="t_hac")
        t = _cols(t)
        L += ["Panel Diebold-Mariano t-statistics (cross-sectionally averaged QLIKE differences, Newey-West; "
              "negative = model_a more accurate; squared-return proxy):", "", md_table(t.reset_index(), "{:+.2f}"), ""]
        x = pan[(pan.assets != "all") & (pan.proxy == "sq") & pan.hypothesis.isin(["V2", "V3", "V4"])]
        x = x[((x.model_a == "garch_t") & (x.model_b == "ewma")) | ((x.model_a == "gjr_t") & (x.model_b == "garch_t")) | ((x.model_a == "garch_t") & (x.model_b == "garch_n"))]
        t = x.pivot_table(index=["model_a", "model_b", "assets"], columns=["period", "window"], values="t_hac")
        t = _cols(t)
        L += ["By market:", "", md_table(t.reset_index(), "{:+.2f}"), ""]
        x = pan[(pan.assets == "all") & (pan.subset != "all") & (pan.proxy == "sq")]
        x = x[x.model_b.isin(["ewma", "garch_t", "garch_n"]) & x.model_a.isin(["garch_t", "gjr_t"])]
        t = x.pivot_table(index=["model_a", "model_b", "subset"], columns=["period", "window"], values="t_hac")
        t = _cols(t)
        L += ["By causal market-volatility regime (V5):", "", md_table(t.reset_index(), "{:+.2f}"), ""]
        x = pan[(pan.assets == "all") & (pan.subset == "all") & (pan.proxy == "gk")]
        if len(x):
            t = x.pivot_table(index=["hypothesis", "model_a", "model_b"], columns=["period", "window"], values="t_hac")
            t = _cols(t)
            L += ["Sensitivity: Garman-Klass range proxy (US + JPX assets with OHLC; *biased*, omits overnight moves):", "",
                  md_table(t.reset_index(), "{:+.2f}"), ""]
        mz = pd.read_csv(vd / "volforecast_mincer_zarnowitz_median.csv")
        L += ["Mincer-Zarnowitz regressions of the squared-return proxy on the forecast (medians across assets):", "",
              md_table(mz, "{:.3f}"), ""]
        ds = pd.read_csv(vd / "volforecast_dm_shares.csv")
        ds = ds[(ds.proxy == "sq")]
        t = ds.pivot_table(index=["hypothesis", "model_a", "model_b"], columns=["period", "window"], values="share_a_better_BH")
        t = _cols(t)
        L += ["Per-asset DM: share of assets where model_a is significantly better after BH-FDR (q = 0.10):", "",
              md_table(t.reset_index(), "{:.2f}"), ""]
        VF.fig_qlike(vs, fig / "v04_qlike_vs_ewma.png", VOL_MODELS,
                     f"Average across {len(fs.assets)} assets of each model's out-of-sample QLIKE minus EWMA's (QLIKE "
                     f"differences are scale-free). Hollow: development (rows {split['dev_start']}-{split['holdout_start'] - 1}); "
                     f"filled: holdout ({split['holdout_start']}-{split['end'] - 1}).")
        VF.fig_mcs(vs, fig / "v05_mcs_inclusion.png", VOL_MODELS)
        eng = engine(cfg, "assets", prepared)
        show = [s for s in ("LME_CA_Close", "FX_AUDUSD") if s in eng["names"]] or list(eng["names"])[:2]
        if show:
            from ..volatility.engine import realised

            k21 = eng["aggs"].index("cum21")
            real, fc = {}, {}
            for s in show:
                i = eng["names"].index(s)
                r = fs.returns[s].to_numpy(dtype=float)
                rv = realised(r, {"cum21": (1, 21)})[:, 0]
                real[s] = pd.Series(np.sqrt(rv * 252 / 21)).ffill().to_numpy()
                fc[s] = {m: pd.Series(np.sqrt(eng["F"][i, :, eng["models"].index(m), k21] * 252 / 21)).to_numpy() for m in ("ewma", "garch_t")}
            VF.fig_vol_paths(np.asarray(dates), real, fc, show, hmark, fig / "v06_vol_forecast_paths.png")

    # ------------------------------------------------------------------ Part III
    for tag in ("dev_holdout", "dev"):
        st = _read(vd / f"returns_stability_{tag}.csv")
        if st is None:
            continue
        periods = ["dev", "holdout"] if tag == "dev_holdout" else ["dev"]
        pr = pd.read_csv(vd / f"returns_paired_{tag}.csv")
        L += [f"## Part III. Return forecasting with volatility information ({' + '.join(periods)})", ""]
        cols = ["period", "model", "mean_ic", "mean_ci_lo", "mean_ci_hi", "t_hac", "ic_ir", "std_ic", "frac_pos", "worst_rolling126", "share_rolling126_negative"]
        L += ["Accuracy and stability (daily rank IC over all targets):", "", md_table(st[cols], "{:.4f}"), ""]
        pr["95% CI"] = [f"[{a:.4f}, {b:.4f}]" for a, b in zip(pr.ci_lo, pr.ci_hi)]
        L += ["Pre-registered paired comparisons (Holm-adjusted p for the primary family R1-R3):", "",
              md_table(pr[["period", "comparison", "model_a", "model_b", "n_dates", "mean_diff", "95% CI", "t_hac", "p_hac", "holm_p"]], "{:.4f}"), ""]
        rg = pd.read_csv(vd / f"returns_regime_{tag}.csv")
        t = rg.pivot_table(index=["comparison", "period"], columns="regime", values="mean_diff").reindex(columns=["low", "mid", "high"])
        L += ["ΔIC by causal market-volatility regime (R6):", "", md_table(t.reset_index(), "{:+.4f}"), ""]
        tt = pd.read_csv(vd / f"returns_target_vol_tercile_{tag}.csv")
        t = tt.pivot_table(index=["comparison", "period"], columns="target_vol_tercile", values="mean_diff").reindex(columns=["low", "mid", "high"])
        L += ["ΔIC within ex-ante target-volatility terciles (R6):", "", md_table(t.reset_index(), "{:+.4f}"), ""]
        ms = pd.read_csv(vd / f"returns_mcs_spa_{tag}.csv")
        L += ["Model Confidence Set (90%, loss = −daily IC) over target-level arms, and Hansen SPA p-value:", "", md_table(ms, "{:.3f}"), ""]
        arms = [m for m in ["hist_mean", "tgbm_R", "tgbm_RV", "tgbm_RVs", "tgbm_RC", "tgbm_RVC", "tgbm_R_garch", "tgbm_R_none",
                            "tridge_R", "tridge_RV", "tridge_RC", "tridge_RVC"] if m in set(st.model)]
        suffix = "" if tag == "dev_holdout" else "_dev"
        VF.fig_arms(st, fig / f"v07_return_arms{suffix}.png", arms, periods)
        comps = [c for c in pr.comparison.unique() if c.startswith(("R1", "R2", "R3"))] or list(pr.comparison.unique())[:3]
        last = periods[-1]
        VF.fig_delta_by(rg[rg.period == last], "regime", ["low", "mid", "high"], fig / f"v08_delta_by_market_vol{suffix}.png",
                        f"ΔIC by market-volatility regime ({last})", comps)
        VF.fig_delta_by(tt[tt.period == last], "target_vol_tercile", ["low", "mid", "high"], fig / f"v09_delta_by_target_vol{suffix}.png",
                        f"ΔIC by target-volatility tercile ({last})", comps)
        daily = pd.read_csv(vd / f"returns_daily_ic_{tag}.csv", index_col=0)
        daily.index = dates
        VF.fig_rolling(daily, ["tgbm_R", "tgbm_RV", "tgbm_RVC", "tgbm_R_garch"], hmark, fig / f"v10_rolling_ic{suffix}.png")
        break
    imp = _read(vd / "importance_tgbm_RVC.csv")
    if imp is not None:
        VF.fig_group_importance(imp, fig / "v11_group_importance.png")
        L += ["## Feature-group gain shares (tgbm_RVC refit at the holdout start)", "",
              md_table(imp.groupby("group")["gain_share"].sum().reset_index(), "{:.3f}"), "",
              md_table(imp.sort_values("gain_share", ascending=False).head(15), "{:.4f}"), ""]
    L += ["## Figures", ""] + [f"- `figures/{p.name}`" for p in sorted(fig.glob("v*.png"))]
    path = out / "vol_tables.md"
    path.write_text("\n".join(L) + "\n")
    log.info("volatility report -> %s", path)
    return path


def run_importance(cfg: dict, arm: str = "tgbm_RVC") -> pd.DataFrame:
    """Refit one target-level arm once on all labels observable at the holdout start."""
    from ..models import FitContext, make_model
    from ..models.target_models import get_target_features
    from .runner import prepare, resolve_split

    md, fs, panel = prepare(cfg)
    split = resolve_split(cfg, panel)
    spec = next(s for s in cfg["models"] if s["name"] == arm)
    model = make_model(spec["type"], arm, spec.get("params", {}), n_jobs=-1, cfg=cfg)
    model.fit(panel, FitContext(tau=split["holdout_start"], first_train=split["first_train"], feature_mask=None,
                                seed=int(cfg.get("seed", 42))))
    tf = get_target_features(panel, cfg)
    names = [n for n, k in zip(tf.names, model.mask_) if k]
    groups = [g for g, k in zip(tf.groups, model.mask_) if k]
    imp = np.mean([v / v.sum() for v in model.importance().values()], axis=0)
    df = pd.DataFrame({"feature": names, "group": groups, "gain_share": imp})
    df.to_csv(vol_dir(cfg) / f"importance_{arm}.csv", index=False)
    return df
